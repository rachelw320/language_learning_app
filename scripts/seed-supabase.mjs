/**
 * Turns src/data/cards.json into supabase/seed.sql, which creates the cards table and inserts every card.
 * Run the sql in the supabase dashboard (sql editor). It's safe to run again - existing cards get updated, not duplicated.
 *
 * Usage: npm run seed
 */

import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_PATH = join(ROOT, 'supabase/seed.sql');

const cards = JSON.parse(readFileSync(join(ROOT, 'src/data/cards.json'), 'utf8'));

/** A quoted sql string, with any single quotes doubled up */
function sqlString(value) {
	if (value === null || value === undefined) {
		return 'NULL';
	}
	return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlArray(values) {
	if (!values || values.length === 0) {
		return 'ARRAY[]::text[]';
	}
	return `ARRAY[${values.map(sqlString).join(', ')}]`;
}

function sqlJson(value) {
	return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

const schema = `-- Creates the cards table and fills it from src/data/cards.json.
-- Generated by scripts/seed-supabase.mjs, so edit the json and re-run that rather than changing this file.
-- Run it in the supabase dashboard -> sql editor. Safe to run again, existing cards get updated.

CREATE TABLE IF NOT EXISTS cards (
  id                    TEXT PRIMARY KEY,
  category              TEXT NOT NULL,
  additional_categories TEXT[],
  "order"               INTEGER NOT NULL,
  deck                  TEXT,
  english               TEXT NOT NULL,
  arabic                TEXT NOT NULL,
  transliteration       TEXT NOT NULL,
  accepted              TEXT[] NOT NULL DEFAULT '{}',
  arabic_variants       TEXT[] NOT NULL DEFAULT '{}',
  audio                 JSONB NOT NULL DEFAULT '{"ar":"","en":""}',
  tags                  TEXT[] NOT NULL DEFAULT '{}',
  notes                 TEXT NOT NULL DEFAULT ''
);

-- Indexes for the category and tag lookups
CREATE INDEX IF NOT EXISTS idx_cards_category ON cards(category);
CREATE INDEX IF NOT EXISTS idx_cards_order ON cards("order");
CREATE INDEX IF NOT EXISTS idx_cards_tags ON cards USING GIN(tags);
CREATE INDEX IF NOT EXISTS idx_cards_additional_categories ON cards USING GIN(additional_categories) WHERE additional_categories IS NOT NULL;

-- Anyone can read the cards, the app uses the public anon key
ALTER TABLE cards ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Cards are publicly readable" ON cards;
CREATE POLICY "Cards are publicly readable" ON cards
  FOR SELECT USING (true);

-- The cards themselves
`;

const inserts = cards.map(
	(card) => `INSERT INTO cards
  (id, category, additional_categories, "order", deck, english, arabic, transliteration, accepted, arabic_variants, audio, tags, notes)
VALUES
  (${sqlString(card.id)}, ${sqlString(card.category)}, ${card.additionalCategories ? sqlArray(card.additionalCategories) : 'NULL'},
   ${card.order}, ${card.deck ? sqlString(card.deck) : 'NULL'},
   ${sqlString(card.english)}, ${sqlString(card.arabic)}, ${sqlString(card.transliteration)},
   ${sqlArray(card.accepted)}, ${sqlArray(card.arabicVariants)},
   ${sqlJson(card.audio)}, ${sqlArray(card.tags)}, ${sqlString(card.notes)})
ON CONFLICT (id) DO UPDATE SET
  category = EXCLUDED.category,
  additional_categories = EXCLUDED.additional_categories,
  "order" = EXCLUDED."order",
  deck = EXCLUDED.deck,
  english = EXCLUDED.english,
  arabic = EXCLUDED.arabic,
  transliteration = EXCLUDED.transliteration,
  accepted = EXCLUDED.accepted,
  arabic_variants = EXCLUDED.arabic_variants,
  audio = EXCLUDED.audio,
  tags = EXCLUDED.tags,
  notes = EXCLUDED.notes;`,
);

const footer = `\n\n-- Should say ${cards.length}\nSELECT COUNT(*) AS total_cards FROM cards;\n`;

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, schema + inserts.join('\n\n') + footer);
console.log(`Wrote supabase/seed.sql with ${cards.length} cards`);
